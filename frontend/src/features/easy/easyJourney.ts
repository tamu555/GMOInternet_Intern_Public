/**
 * 「サイト公開までの全体図」— かんたんモードのゴールと、そこに至る 3 つの部品。
 *
 * ⚠️ このモジュールが生まれた理由（消さないこと）:
 * かんたんモードの進捗バーは 6 段の最後が「つなぐ」で終わっていた。つまり
 * バーが示すゴールは「ウィザードを最後まで押し切ること」であって、利用者が
 * 本当に欲しい「サイトが見られる状態」ではなかった。その結果、初心者から
 * 次の 3 つが同時に分からないという指摘が出た:
 *   1. 「つなぐ設定」とは何なのか
 *   2. 「つなぐ設定」と「DNS設定」は別物なのか
 *   3. サイトを公開するのに、それは必ずやらないといけないのか
 * 1 と 2 は言葉の問題で、3 は「ゴールがどこか」の問題である。ゴールを
 * 「サイト公開」に置き直すと、3 の答えが構造として出てくる（公開に必要な
 * 部品の 1 つだから必須）ので、この 3 つはまとめてここで面倒を見る。
 *
 * ⚠️ 答えは「つなぐ設定 = DNS設定」。別物ではなく、同じものの言い換えである。
 * アプリ内には「つなぐ」系の平易な語と「DNS設定」という用語が両方あり、
 * どちらか一方に寄せると（a）用語を消すと外の世界の情報と接続できなくなる
 * （b）用語だけにすると初心者が読めない、のどちらかで詰む。仕様 §1.4 の
 * 「用語を削除せず注釈する」に従い、**平易な語を主、用語を括弧で従**にした
 * `つなぐ設定（DNS設定）` を正の呼び方とする。{@link CONNECT_TERM} が唯一の正。
 *
 * ⚠️ 「② サイトの置き場所」を全体図から省かないこと。これは当サービスでは
 * 用意できず、利用者が別のサービスで自分で契約する部品である（`dns/
 * connectMessages.ts` の PREPARE_SEQUENCE と同じ事実）。ここを描かずに
 * ゴールだけ「サイト公開」にすると、置き場所を持っていない人に対して
 * 「⑥まで押せば公開される」という嘘をつくことになる。3 つのうち 1 つが
 * 自分の担当だと最初に分かっていることが、この図の一番の仕事。
 */

/** その部品を誰が用意するか。 */
export type EasyJourneyOwner =
  /** このかんたんモードの中で終わる。 */
  | 'here'
  /** 利用者が別のサービスで用意する（当サービスの外）。 */
  | 'yourself'

export type EasyJourneyPart = {
  id: 'domain' | 'place' | 'connect'
  /** 初心者の言葉での名前。技術用語は `term` に分ける。 */
  title: string
  /**
   * 併記する語。**外の世界（契約したサービスの説明画面や検索結果）で、この
   * 部品が何と呼ばれているか**を書く。用語を知らないと、外で同じものの話を
   * されても同じものだと気づけない。
   *
   * ⚠️ `analogy` の言い換えを入れないこと。両者は同じ行に並ぶので、
   * 「ドメイン（住所の名前）たとえるなら「住所」」のように同じことを 2 度言う。
   */
  term: string
  /**
   * たとえの 1 語。**3 つ並べたときに 1 つの話として成立すること**だけを狙う。
   *
   * ⚠️ 3 つを別々に考えないこと。かつて「住所 / 建物 / 電話帳」だったが、
   * 現実には**住所が分かれば建物にはたどり着ける**ので、初心者に「住所を
   * 買ったのに、なぜさらに電話帳が要るのか」を作ってしまっていた。電話帳が
   * 引くのは住所→建物ではなく**名前→場所**なので、① は「名前」でなければ
   * ならない（① の body も「あなただけの名前です」と言っている）。
   * 「お店の名前 → お店の建物 → 電話帳」なら 3 つが 1 つの話として閉じる。
   */
  analogy: string
  /** 1 文の説明。「これが無いとどうなるか」まで言い切る。 */
  body: string
  owner: EasyJourneyOwner
  /** 誰がどこで用意するかの 1 行。`owner` の言い換えではなく、場所を言う。 */
  ownerNote: string
}

